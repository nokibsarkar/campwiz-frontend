#!/usr/bin/env node
/**
 * Generates i18n/languages.generated.ts from the i18n/locales/ subdirectories.
 * Excludes the 'qqq' documentation pseudo-locale.
 *
 * Usage: node scripts/generate-languages.js
 */
const fs = require('fs');
const path = require('path');

const localesDir = path.join(__dirname, '..', 'i18n', 'locales');
const outputFile = path.join(__dirname, '..', 'i18n', 'languages.generated.ts');

const languages = fs.readdirSync(localesDir)
    .filter(entry => entry !== 'qqq' && fs.statSync(path.join(localesDir, entry)).isDirectory())
    .sort();

const content = `// Auto-generated by scripts/generate-languages.js — do not edit manually.
export const languages = ${JSON.stringify(languages, null, 4)};
`;

fs.writeFileSync(outputFile, content);
console.log(`Generated ${outputFile} with ${languages.length} languages.`);
